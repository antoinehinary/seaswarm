"""Write random evaluation scenarios to scenarios/generated/gen_XXX.yaml.

python scripts/generate_scenarios.py --n 60 --seed 0
"""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml

from seaswarm.config import load_default_config
from seaswarm.eval.scenario import generate_scenario


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    """Parse the command line."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--n", type=int, default=60)
    parser.add_argument("--seed", type=int, default=0, help="master seed of the scenario set")
    parser.add_argument("--out", type=Path, default=Path("scenarios/generated"))
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    """Generate and write the scenarios."""
    args = parse_args(argv)
    defaults = load_default_config()
    args.out.mkdir(parents=True, exist_ok=True)
    for i in range(args.n):
        scenario = generate_scenario(i, args.seed, defaults)
        path = args.out / f"{scenario.id}.yaml"
        header = f"# Generated by scripts/generate_scenarios.py --seed {args.seed}; do not edit.\n"
        path.write_text(header + yaml.safe_dump(scenario.model_dump(mode="json"), sort_keys=False))
    print(f"wrote {args.n} scenarios to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
